import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
const db = new PGlite();
await db.exec(`create role anon; create role authenticated; create role service_role bypassrls;
create schema auth; create table auth.users(id uuid primary key); create table congressman(id bigint primary key);
create table brief_pipeline_settings(id boolean primary key, daily_draft_limit int, daily_budget_usd numeric);
insert into brief_pipeline_settings values(true,2,5);
create table brief_api_call(id uuid default gen_random_uuid(),job_id bigint,model text,stage text,reserved_usd numeric,actual_usd numeric,budget_day date default current_date);
`);
for(const file of ['20260820192741_replace_articles_with_briefs.sql','20260906235854_fec_committee_contributions.sql','20260920195644_fec_individual_contributions.sql','20261011005959_contribution_overviews.sql','20261101121359_continuous_contribution_briefs.sql'])
 await db.exec(readFileSync(new URL(`../../../../apps/web/supabase/migrations/${file}`,import.meta.url),'utf8'));
const scalar=async sql=>Object.values((await db.query(sql)).rows[0])[0];
const draft=(member,key)=>({title:'Funding explained',slug:`funding-${member}-${key}`,dek:'What voters can infer',primary_item_type:'campaign_finance',primary_item_id:member,contribution_cycle:2026,points:[{text:'A'},{text:'B'},{text:'C'}],sources:[{id:'fec',url:'https://www.fec.gov'}],context_markdown:'Explainer',generation_metadata:{trigger:'contribution-continuous',fingerprint:key.repeat(64),verification:{checkedAt:new Date().toISOString()},selection:{selected:true}}});
const stage=async d=>(await db.query('select stage_contribution_brief($1::jsonb) as id',[JSON.stringify(d)])).rows[0].id;
await db.exec('insert into congressman values(1),(2),(3)');
await db.exec("insert into brief(title,primary_item_type,primary_item_id,contribution_cycle) values('Legacy', 'campaign_finance',1,2026)");
assert.equal(await stage(draft(1,'a')),0,'do not duplicate a pending manual draft');
await db.exec("update brief set status='archived'");
const first=await stage(draft(1,'a'));assert.ok(first>0);
assert.equal(await stage(draft(1,'b')),0,'do not accumulate review drafts');
await db.exec(`update brief set status='archived' where id=${first}`);
assert.equal(await stage(draft(1,'a')),0,'archived evidence stays deduplicated');
await db.exec("select reserve_brief_api_call(1,'test','extraction',0.01)");
assert.equal(await stage(draft(2,'b')),null,'AI admission shares daily allowance');
await assert.rejects(()=>db.exec("select reserve_brief_api_call(2,'test','extraction',0.01)"),/daily draft limit/);
await db.exec('update brief_pipeline_settings set daily_draft_limit=3');
const followup=await stage(draft(1,'b'));assert.ok(followup>first,'new evidence allows a follow-up in the same cycle');
assert.equal(await scalar(`select status from brief where id=${followup}`),'review');
assert.equal(await scalar(`select published_at from brief where id=${followup}`),null);
await db.exec('set role anon');
assert.equal(await scalar('select count(*) from brief'),0);
await assert.rejects(()=>stage(draft(3,'c')),/permission denied/);
await db.exec('reset role; set role authenticated');
await assert.rejects(()=>stage(draft(3,'c')),/permission denied/);
await db.close(); console.log('Continuous contribution database checks passed.');
