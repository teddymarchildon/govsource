-- Congress provides one predominant policy area per bill. Preserve it on the
-- bill row and translate it into one approved primary GovSource topic.
insert into public.bill_topic (
    bill_id,
    topic_id,
    assignment_source,
    assignment_status,
    confidence,
    is_primary,
    evidence,
    reviewed_at
)
select
    bill.id,
    mapping.topic_id,
    'source_mapping',
    'approved',
    1.000,
    true,
    jsonb_build_object(
        'source_system', mapping.source_system,
        'source_value', bill.policy_area
    ),
    now()
from public.bill
join public.topic_source_mapping mapping
  on mapping.source_system = 'congress_policy_area'
 and mapping.source_value = bill.policy_area
 and mapping.is_primary;

-- Keep future bill syncs aligned with the canonical mapping without replacing
-- any independently assigned editorial, rules-based, or AI-suggested topics.
create or replace function public.sync_bill_topics_from_policy_area()
returns trigger
language plpgsql
security invoker
set search_path = ''
as $$
begin
    delete from public.bill_topic
    where bill_id = new.id
      and assignment_source = 'source_mapping';

    insert into public.bill_topic (
        bill_id,
        topic_id,
        assignment_source,
        assignment_status,
        confidence,
        is_primary,
        evidence,
        reviewed_at
    )
    select
        new.id,
        mapping.topic_id,
        'source_mapping',
        'approved',
        1.000,
        not exists (
            select 1
            from public.bill_topic existing
            where existing.bill_id = new.id
              and existing.assignment_status = 'approved'
              and existing.is_primary
        ),
        jsonb_build_object(
            'source_system', mapping.source_system,
            'source_value', new.policy_area
        ),
        now()
    from public.topic_source_mapping mapping
    where mapping.source_system = 'congress_policy_area'
      and mapping.source_value = new.policy_area
      and mapping.is_primary;

    return new;
end;
$$;

create trigger sync_public_bill_topics_from_policy_area
after insert or update of policy_area on public.bill
for each row
execute function public.sync_bill_topics_from_policy_area();

