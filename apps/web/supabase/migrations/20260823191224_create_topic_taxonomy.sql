create policy "Public can read active topics"
on public.topic
for select
to anon, authenticated
using (status = 'active');

create policy "Public can read approved bill topics"
on public.bill_topic
for select
to anon, authenticated
using (
    assignment_status = 'approved'
    and exists (
        select 1 from public.topic
        where topic.id = bill_topic.topic_id
          and topic.status = 'active'
    )
);

create policy "Public can read approved agency document topics"
on public.agency_document_topic
for select
to anon, authenticated
using (
    assignment_status = 'approved'
    and exists (
        select 1 from public.topic
        where topic.id = agency_document_topic.topic_id
          and topic.status = 'active'
    )
);

create policy "Public can read approved court case topics"
on public.cluster_topic
for select
to anon, authenticated
using (
    assignment_status = 'approved'
    and exists (
        select 1 from public.topic
        where topic.id = cluster_topic.topic_id
          and topic.status = 'active'
    )
);

create policy "Public can read topics for live briefs"
on public.brief_topic
for select
to anon, authenticated
using (
    assignment_status = 'approved'
    and exists (
        select 1 from public.topic
        where topic.id = brief_topic.topic_id
          and topic.status = 'active'
    )
    and exists (
        select 1 from public.brief
        where brief.id = brief_topic.brief_id
          and brief.status in ('published', 'scheduled')
          and brief.slug is not null
          and brief.published_at is not null
          and brief.published_at <= now()
    )
);

