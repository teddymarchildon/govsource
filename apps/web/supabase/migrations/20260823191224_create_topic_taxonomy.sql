-- Canonical, cross-branch GovSource topics and record assignments.
-- Source-native classifications such as bill.policy_area remain unchanged.
set search_path = public;

create table public.topic (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    parent_topic_id bigint references public.topic (id) on delete set null,
    slug text not null unique,
    name text not null unique,
    short_name text,
    description text not null,
    seo_title text not null,
    seo_description text not null,
    status text not null default 'draft',
    display_order smallint not null default 0,
    constraint topic_slug_check check (slug ~ '^[a-z0-9]+(?:-[a-z0-9]+)*$'),
    constraint topic_name_check check (char_length(name) between 2 and 80),
    constraint topic_status_check check (status in ('draft', 'active', 'archived')),
    constraint topic_display_order_check check (display_order >= 0),
    constraint topic_no_self_parent_check check (parent_topic_id is distinct from id)
);

create index topic_parent_topic_id_idx
    on public.topic (parent_topic_id)
    where parent_topic_id is not null;

create index topic_public_directory_idx
    on public.topic (display_order, name)
    where status = 'active';

create table public.topic_source_mapping (
    topic_id bigint not null references public.topic (id) on delete cascade,
    source_system text not null,
    source_value text not null,
    is_primary boolean not null default true,
    created_at timestamptz not null default now(),
    primary key (source_system, source_value, topic_id),
    constraint topic_source_mapping_source_system_check check (
        source_system in ('congress_policy_area', 'brief_policy_area')
    ),
    constraint topic_source_mapping_source_value_check check (char_length(source_value) > 0)
);

create unique index topic_source_mapping_one_primary_idx
    on public.topic_source_mapping (source_system, source_value)
    where is_primary;

create index topic_source_mapping_topic_id_idx
    on public.topic_source_mapping (topic_id, source_system);

create table public.bill_topic (
    bill_id bigint not null references public.bill (id) on delete cascade,
    topic_id bigint not null references public.topic (id) on delete cascade,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    assignment_source text not null,
    assignment_status text not null default 'suggested',
    confidence numeric(4, 3),
    is_primary boolean not null default false,
    evidence jsonb not null default '{}'::jsonb,
    assigned_by uuid references auth.users (id) on delete set null,
    reviewed_by uuid references auth.users (id) on delete set null,
    reviewed_at timestamptz,
    primary key (bill_id, topic_id),
    constraint bill_topic_assignment_source_check check (
        assignment_source in ('source_mapping', 'rule_based', 'ai_suggested', 'editorial')
    ),
    constraint bill_topic_assignment_status_check check (
        assignment_status in ('suggested', 'approved', 'rejected')
    ),
    constraint bill_topic_confidence_check check (confidence between 0 and 1),
    constraint bill_topic_evidence_check check (jsonb_typeof(evidence) = 'object')
);

